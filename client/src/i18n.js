// A decimal number in a message parameter reads with a comma in Spanish ("0.30" -> "0,30").
const localNumber = (value, index) => (index === 0 && /^-?\d+\.\d+$/.test(String(value)) ? String(value).replace(".", ",") : String(value));

export function makeT(lang) {
  const index = lang === "en" ? 1 : 0;
  // `{{` and `}}` are literal braces (the catalogue writes JSON examples with them); they are set aside while the placeholders are filled.
  const fill = (entry, vars) => {
    let value = (entry[index] ?? entry[0]).replaceAll("{{", "\u0001").replaceAll("}}", "\u0002");
    if (vars) for (const [name, v] of Object.entries(vars)) value = value.replaceAll(`{${name}}`, localNumber(v, index));
    return value.replaceAll("\u0001", "{").replaceAll("\u0002", "}");
  };
  const t = (key, vars) => {
    const entry = D[key];
    if (entry === undefined) return key;
    return fill(entry, vars);
  };
  // A message of the backend: a plain string (free text, shown as it is) or { key, params, text } (formatted in the UI language; the English
  // text is the fallback for a key this build does not know). A parameter may itself be a message.
  // A parameter: a nested message, a job state (worded in the UI language), or the value itself.
  const param = (name, v) => {
    if (v !== null && typeof v === "object") return msg(v);
    if (name === "state" && D[`state_${v}`] !== undefined) return fill(D[`state_${v}`]).toLowerCase();
    return v;
  };
  const msg = (m) => {
    if (m === null || m === undefined || m === "") return "";
    if (typeof m !== "object") return String(m);
    const entry = m.key ? (m.key.startsWith("hint_") ? D[m.key] : D[`msg_${m.key}`] ?? D[`err_${m.key}`]) : undefined;
    if (entry === undefined) return m.text ?? "";
    const vars = {};
    for (const [name, v] of Object.entries(m.params || {})) vars[name] = param(name, v);
    return fill(entry, vars);
  };
  // An error thrown by api.js: the message of its key, else the English text the server sent.
  const error = (e) => {
    if (!e) return "";
    const entry = e.key ? D[`err_${e.key}`] : undefined;
    if (entry === undefined) return e.message || String(e);
    const vars = {};
    for (const [name, v] of Object.entries(e.params || {})) vars[name] = param(name, v);
    return fill(entry, vars);
  };
  // What to do about an error: a message item (translated) or the plain hint the server sent.
  const hint = (e) => {
    if (!e) return "";
    return typeof e.hint === "object" && e.hint ? msg(e.hint) : e.hint || "";
  };
  // The text of a toast or banner for an error: the message and its hint.
  const errorLine = (e) => {
    const base = error(e);
    const extra = hint(e);
    return extra ? `${base} — ${extra}` : base;
  };
  // A job state in a message parameter ("state": "failed") reads in the UI language.
  return Object.assign(t, { msg, error, hint, errorLine });
}

